create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  endpoint text not null unique,
  subscription jsonb not null,
  machine_nos integer[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists push_subscriptions_machine_nos_idx
  on public.push_subscriptions using gin (machine_nos);

-- Browsers never talk directly to these tables. All reads/writes go through server-side Vercel routes.
