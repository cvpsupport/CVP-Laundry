create table if not exists public.machines (
  id bigint generated by default as identity primary key,
  machine_no integer not null unique check (machine_no between 1 and 4),
  name text not null,
  machine_type text not null default 'washer' check (machine_type in ('washer', 'dryer')),
  price_baht integer check (price_baht is null or price_baht >= 0),
  status text not null default 'available' check (status in ('available', 'running', 'finished', 'offline')),
  program text,
  started_at timestamptz,
  end_at timestamptz,
  near_finish_notified_at timestamptz,
  finish_notified_at timestamptz,
  updated_at timestamptz not null default now()
);

